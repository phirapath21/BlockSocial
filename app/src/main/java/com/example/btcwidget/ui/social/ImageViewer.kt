/** Full-screen image: pinch or double-tap to zoom, drag to pan, tap ✕ or Back to close. */
@Composable
fun ImageViewer(url: String, onDismiss: () -> Unit) {
    val uriHandler = LocalUriHandler.current
    var scale by remember { mutableFloatStateOf(1f) }
    var offset by remember { mutableStateOf(Offset.Zero) }
    Dialog(onDismissRequest = onDismiss, properties = DialogProperties(usePlatformDefaultWidth = false)) {
        Box(Modifier.fillMaxSize().background(Color.Black)) {
            AsyncImage(
                model = url,
                contentDescription = "Image",
                contentScale = ContentScale.Fit,
                modifier = Modifier
                    .fillMaxSize()
                    .pointerInput(Unit) {
                        detectTransformGestures { _, pan, zoom, _ ->
                            scale = (scale * zoom).coerceIn(1f, 5f)
                            offset = if (scale == 1f) Offset.Zero else offset + pan
                        }
                    }
                    .pointerInput(Unit) {
                        detectTapGestures(onDoubleTap = {
                            if (scale > 1f) { scale = 1f; offset = Offset.Zero } else scale = 2.5f
                        })
                    }
                    .graphicsLayer {
                        scaleX = scale
                        scaleY = scale
                        translationX = offset.x
                        translationY = offset.y
                    }
            )
            Row(
                Modifier.fillMaxWidth().safeDrawingPadding().padding(8.dp),
                verticalAlignment = Alignment.CenterVertically
            ) {
                Text(
                    "✕", color = Color.White, fontSize = 22.sp,
                    modifier = Modifier.clickable(onClickLabel = "Close", onClick = onDismiss).padding(12.dp)
                )
                Box(Modifier.weight(1f))
                Text(
                    "Open in browser", color = Color.White, fontSize = 14.sp, fontWeight = FontWeight.Bold,
                    modifier = Modifier.clickable { uriHandler.openUri(url) }.padding(12.dp)
                )
            }
        }
    }
}
